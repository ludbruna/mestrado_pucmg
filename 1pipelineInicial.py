def gerar_relatorio(data: pd.DataFrame, target_col: Optional[str] = None) -> Dict[str, Any]:
    """Gera tabelas (e versões HTML) para caracterização de atributos.

    - Assume, por padrão, que a classe é a última coluna.
    - Não altera o DataFrame de entrada.
    """
    if target_col is None:
        target_col = data.columns[-1]

    target_exists = target_col in data.columns
    input_cols = [c for c in data.columns if c != target_col]

    # -------------------------
    # Tabela 1 — Resumo (somente ENTRADA)
    # -------------------------
    n_inst = len(data)
    missing_cells = int(data.isna().sum().sum())
    total_cells = int(data.shape[0] * data.shape[1])
    missing_pct = (missing_cells / total_cells) * 100 if total_cells else 0.0

    qtd_dicot = 0
    qtd_num_disc = 0
    qtd_num_cont = 0
    qtd_cat_nom = 0

    # -------------------------
    # Tabela 3/4/5 — Detalhes (ENTRADA)
    # -------------------------
    tab_dicot: List[Dict[str, Any]] = []
    tab_nom: List[Dict[str, Any]] = []
    tab_num: List[Dict[str, Any]] = []

    for col in input_cols:
        s = data[col]
        nunq = _n_unique_non_null(s)
        if nunq == 0:
            continue

        nome = format_attr_name(data, col)

        # Dicotômico
        if _is_dichotomous(s):
            qtd_dicot += 1
            tab_dicot.append({
                "Atributo": nome,
                "Forma": "numérico" if _is_numeric(s) else "nominal",
                "Opções de resposta": _levels(s),
            })
            continue

        # Numérico (não dicotômico)
        if _is_numeric(s):
            if _is_discrete_numeric(s):
                qtd_num_disc += 1
                tipo = "Discreto"
            else:
                qtd_num_cont += 1
                tipo = "Contínuo"

            vmin, vmax = _min_max(s)
            tab_num.append({
                "Atributo": nome,
                "Tipo": tipo,
                "min": vmin,
                "max": vmax,
            })
            continue

        # Categórico nominal (não dicotômico)
        qtd_cat_nom += 1
        tab_nom.append({
            "Atributo": nome,
            "Cardinalidade": nunq,
            "Opções de resposta": _levels(s),
        })

    resumo = pd.DataFrame([
        {
            "Instâncias": n_inst,
            "Dados ausentes (células)": missing_cells,
            "Dados ausentes (%)": round(missing_pct, 4),
            "Discretos": qtd_num_disc,
            "Contínuos": qtd_num_cont,
            "Dicotômicos": qtd_dicot,
            "Categóricos nominais": qtd_cat_nom,
            "Atributos de entrada": len(input_cols),
        }
    ])

    # -------------------------
    # Tabela 2 — Classe
    # -------------------------
    if target_exists:
        s_y = data[target_col]
        classe_info = pd.DataFrame([
            {
                "Classe": _bold(target_col),
                "Tipo de atributo": _tipo_atributo(s_y),
                "Quantidade de respostas": _n_unique_non_null(s_y),
            }
        ])
    else:
        classe_info = pd.DataFrame([
            {
                "Classe": _bold(str(target_col)),
                "Tipo de atributo": "Não encontrada",
                "Quantidade de respostas": 0,
            }
        ])

    df_dicot = pd.DataFrame(tab_dicot)
    df_nom = pd.DataFrame(tab_nom)
    df_num = pd.DataFrame(tab_num)

    return {
        "tabela_resumo": resumo,
        "tabela_dicotomicos": df_dicot,
        "tabela_nominais": df_nom,
        "tabela_numericos": df_num,
        "tabela_classe": classe_info,
        "html_resumo": to_html_com_titulo(resumo, "Tabela 1 — Resumo geral da base de dados"),
        "html_classe": to_html_com_titulo(classe_info, "Tabela 2 — Caracterização do atributo classe"),
        "html_dicotomicos": to_html_com_titulo(df_dicot, "Tabela 3 — Atributos dicotômicos de entrada"),
        "html_nominais": to_html_com_titulo(df_nom, "Tabela 4 — Atributos categóricos nominais de entrada"),
        "html_numericos": to_html_com_titulo(df_num, "Tabela 5 — Atributos numéricos de entrada"),
    }


