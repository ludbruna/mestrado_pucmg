# Política para valores fora do mapeamento:
# - "error": interrompe
# - "nan": vira NaN
unknown_binary_policy = "error"  # "error" | "nan"

df_enc = df.copy()

for col, mp in binary_mapping.items():
    if col not in df_enc.columns:
        raise KeyError(f"[binário] Coluna não encontrada: {col}")

    # valida se o mapeamento tem exatamente {0,1}
    vals = sorted(set(mp.values()))
    if vals != [0, 1]:
        raise ValueError(f"[binário] {col}: mapping deve ter exatamente valores 0 e 1. Recebido: {vals}")

    observed = set(df_enc[col].dropna().unique().tolist())
    mapped = set(mp.keys())
    unknown_vals = observed - mapped

    if unknown_vals and unknown_binary_policy == "error":
        raise ValueError(f"[binário] {col}: valores não mapeados: {sorted(list(unknown_vals))}")

    df_enc[col] = df_enc[col].map(mp)  # desconhecidos -> NaN
    df_enc[col] = df_enc[col].astype("float")  # preserva NaN

print("Atributos binários codificados:", list(binary_mapping.keys()))
