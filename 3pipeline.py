def list_csv_files(input_dir: str) -> List[str]:
    files = sorted(glob.glob(os.path.join(input_dir, "*.csv")))
    return [f for f in files if os.path.isfile(f)]

def ensure_dir(path: str) -> None:
    os.makedirs(path, exist_ok=True)

def dataset_name_from_path(path: str) -> str:
    base = os.path.basename(path)
    return os.path.splitext(base)[0]

def split_X_y(df: pd.DataFrame, target_col: Optional[str]) -> Tuple[pd.DataFrame, pd.Series, str]:
    if target_col is None:
        target_col = df.columns[-1]
    if target_col not in df.columns:
        raise ValueError(f"TARGET_COL='{target_col}' não existe no CSV.")
    X = df.drop(columns=[target_col]).copy()
    y = df[target_col].copy()
    return X, y, target_col

def get_categorical_cols(X: pd.DataFrame) -> List[str]:
    # Regra (A): apenas colunas object/category
    return list(X.select_dtypes(include=["object", "category"]).columns)

def compute_cardinalities(X: pd.DataFrame, cat_cols: List[str]) -> Dict[str, int]:
    return {c: int(X[c].nunique(dropna=True)) for c in cat_cols}

def metric_triplet(y_true, y_pred) -> Tuple[float, float, float]:
    p = precision_score(y_true, y_pred, zero_division=0)
    r = recall_score(y_true, y_pred, zero_division=0)
    f = f1_score(y_true, y_pred, zero_division=0)
    return p, r, f

