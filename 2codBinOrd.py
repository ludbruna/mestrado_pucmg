def _is_nominal_series(s: pd.Series) -> bool:
    return (
        pd.api.types.is_object_dtype(s)
        or pd.api.types.is_categorical_dtype(s)
        or pd.api.types.is_bool_dtype(s)
    )

def _sorted_unique_values(s: pd.Series, max_show: int = 80) -> List[Any]:
    vals = s.dropna().unique().tolist()
    try:
        vals = sorted(vals)
    except Exception:
        pass
    return vals if len(vals) <= max_show else (vals[:max_show] + ["..."])

