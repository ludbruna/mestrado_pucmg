def _is_sklearn_ohe_ct(encoder) -> bool:
    return isinstance(encoder, ColumnTransformer) and hasattr(encoder, "named_transformers_") and ("cat" in encoder.named_transformers_)

def _extract_ohe(encoder: ColumnTransformer) -> OneHotEncoder:
    return encoder.named_transformers_["cat"]

def mapping_onehot_or_dummy_train_test(
    encoder: ColumnTransformer,
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    cat_cols: List[str],
    encoder_name: str,
    out_dir: str,
) -> None:
    ohe = _extract_ohe(encoder)
    learned = {col: list(ohe.categories_[i]) for i, col in enumerate(cat_cols)}

    dropped = {}
    try:
        drop_idx = ohe.drop_idx_
        if drop_idx is not None:
            for i, col in enumerate(cat_cols):
                idx = drop_idx[i]
                if idx is not None and idx >= 0:
                    dropped[col] = learned[col][idx]
    except Exception:
        dropped = {}

    def _build(split_name: str, X: pd.DataFrame) -> pd.DataFrame:
        rows = []
        for col in cat_cols:
            seen = pd.Series(X[col]).drop_duplicates().tolist()
            for cat in seen:
                if cat in learned[col]:
                    if col in dropped and cat == dropped[col]:
                        rows.append({
                            "split": split_name,
                            "encoder": encoder_name,
                            "feature": col,
                            "category": cat,
                            "encoded_feature": "",
                            "encoded_value": "",
                            "note": "dropped_reference"
                        })
                    else:
                        # nome compatível com OneHotEncoder (sem prefixo do ColumnTransformer)
                        feat_name = f"{col}_{cat}"
                        # no output completo do ColumnTransformer, normalmente vira: cat__<feat_name>
                        rows.append({
                            "split": split_name,
                            "encoder": encoder_name,
                            "feature": col,
                            "category": cat,
                            "encoded_feature": f"cat__{feat_name}",
                            "encoded_value": 1,
                            "note": ""
                        })
                else:
                    rows.append({
                        "split": split_name,
                        "encoder": encoder_name,
                        "feature": col,
                        "category": cat,
                        "encoded_feature": "",
                        "encoded_value": "",
                        "note": "unknown_in_train"  # handle_unknown='ignore' => vetor de zeros
                    })
        return pd.DataFrame(rows)

    save_csv(_build("train", X_train), os.path.join(out_dir, f"mapping_{encoder_name}_train.csv"))
    save_csv(_build("test",  X_test),  os.path.join(out_dir, f"mapping_{encoder_name}_test.csv"))

def _infer_feature_output_cols(encoded_cols: List[str], feature: str) -> List[str]:
    # Prioridade: coluna única com mesmo nome (ex.: count/ordinal/target/catboost/loo)
    if feature in encoded_cols:
        return [feature]
    # Expansões típicas (binary/helmert): feature_0, feature_1, ...
    pref = feature + "_"
    return [c for c in encoded_cols if c.startswith(pref)]

def mapping_category_encoders_train_test(
    encoder,
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    cat_cols: List[str],
    encoder_name: str,
    out_dir: str,
) -> None:
    baseline = make_baseline_row(X_train)
    enc_baseline = encoder.transform(baseline)
    if not isinstance(enc_baseline, pd.DataFrame):
        enc_baseline = pd.DataFrame(enc_baseline)
    encoded_cols = list(enc_baseline.columns)

    def _build(split_name: str, X: pd.DataFrame) -> pd.DataFrame:
        rows = []
        for feat in cat_cols:
            out_cols = _infer_feature_output_cols(encoded_cols, feat)
            cats = pd.Series(X[feat]).drop_duplicates().tolist()
            for cat in cats:
                tmp = baseline.copy()
                tmp.loc[tmp.index[0], feat] = cat
                enc_tmp = encoder.transform(tmp)
                if not isinstance(enc_tmp, pd.DataFrame):
                    enc_tmp = pd.DataFrame(enc_tmp, columns=encoded_cols)
                for oc in out_cols:
                    rows.append({
                        "split": split_name,
                        "encoder": encoder_name,
                        "feature": feat,
                        "category": cat,
                        "encoded_feature": oc,
                        "encoded_value": enc_tmp.loc[enc_tmp.index[0], oc],
                    })
        return pd.DataFrame(rows)

    save_csv(_build("train", X_train), os.path.join(out_dir, f"mapping_{encoder_name}_train.csv"))
    save_csv(_build("test",  X_test),  os.path.join(out_dir, f"mapping_{encoder_name}_test.csv"))

def mapping_hash_train_test(
    encoder,
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    cat_cols: List[str],
    encoder_name: str,
    out_dir: str,
) -> None:
    # train: combinações distintas + freq
    train_cats = X_train[cat_cols].copy()
    train_freq = train_cats.value_counts(dropna=False).reset_index(name="freq_train")
    train_vec  = encoder.transform(train_freq[cat_cols])

    # test: combinações distintas + freq
    test_cats = X_test[cat_cols].copy()
    test_freq = test_cats.value_counts(dropna=False).reset_index(name="freq_test")
    test_vec  = encoder.transform(test_freq[cat_cols])

    df_train = pd.concat([train_freq[cat_cols], train_vec.reset_index(drop=True), train_freq[["freq_train"]]], axis=1)
    df_test  = pd.concat([test_freq[cat_cols],  test_vec.reset_index(drop=True),  test_freq[["freq_test"]]], axis=1)

    save_csv(df_train, os.path.join(out_dir, f"mapping_{encoder_name}_train.csv"))
    save_csv(df_test,  os.path.join(out_dir, f"mapping_{encoder_name}_test.csv"))

