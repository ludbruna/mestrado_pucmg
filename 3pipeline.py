import hashlib

def _hash_bucket(token: str, algo: str, n_buckets: int) -> int:
    b = token.encode("utf-8", errors="ignore")
    if algo == "md5":
        h = hashlib.md5(b).digest()
    elif algo == "sha256":
        h = hashlib.sha256(b).digest()
    else:
        raise ValueError("algo deve ser 'md5' ou 'sha256'")
    return int.from_bytes(h, byteorder="big", signed=False) % n_buckets

def _as_token(val) -> str:
    if pd.isna(val):
        return "nan"
    return str(val)

class HashGroupedEncoder(BaseEstimator, TransformerMixin):
    """Todas as colunas categóricas contribuem para o mesmo vetor final (n_components)."""
    def __init__(self, cols: List[str], algo: str = "md5", n_components: int = 8):
        self.cols = list(cols)
        self.algo = algo
        self.n_components = int(n_components)

    def fit(self, X, y=None):
        return self

    def transform(self, X):
        X = pd.DataFrame(X).copy()
        n = len(X)
        out = np.zeros((n, self.n_components), dtype=np.float64)
        for i in range(n):
            for col in self.cols:
                token = f"{col}={_as_token(X.iloc[i][col])}"
                j = _hash_bucket(token, self.algo, self.n_components)
                out[i, j] += 1.0
        colnames = [f"COL_{k+1}" for k in range(self.n_components)]
        return pd.DataFrame(out, columns=colnames, index=X.index)

class HashSeparateEncoder(BaseEstimator, TransformerMixin):
    """Cada coluna gera seu próprio vetor (n_components) e depois concatena."""
    def __init__(self, cols: List[str], algo: str = "md5", n_components: int = 8):
        self.cols = list(cols)
        self.algo = algo
        self.n_components = int(n_components)

    def fit(self, X, y=None):
        return self

    def transform(self, X):
        X = pd.DataFrame(X).copy()
        n = len(X)
        blocks = []
        for col in self.cols:
            out = np.zeros((n, self.n_components), dtype=np.float64)
            for i in range(n):
                token = f"{col}={_as_token(X.iloc[i][col])}"
                j = _hash_bucket(token, self.algo, self.n_components)
                out[i, j] += 1.0
            blocks.append(out)
        mat = np.concatenate(blocks, axis=1) if blocks else np.zeros((n, 0), dtype=np.float64)
        colnames = [f"COL_{k+1}" for k in range(mat.shape[1])]
        return pd.DataFrame(mat, columns=colnames, index=X.index)

class HashMixedGroupedEncoder(BaseEstimator, TransformerMixin):
    """Mista (agrupada): cols com card < threshold usam n_low; cols com card >= threshold usam n_high.
    Saída = concatenação [parte_low (n_low), parte_high (n_high)] com tamanhos FIXOS.
    """
    def __init__(self, cols: List[str], algo: str = "md5", threshold: int = 100, n_low: int = 8, n_high: int = 32):
        self.cols = list(cols)
        self.algo = algo
        self.threshold = int(threshold)
        self.n_low = int(n_low)
        self.n_high = int(n_high)
        self.low_cols_ = []
        self.high_cols_ = []

    def fit(self, X, y=None):
        X = pd.DataFrame(X)
        cards = {c: int(X[c].nunique(dropna=True)) for c in self.cols}
        self.low_cols_ = [c for c in self.cols if cards.get(c, 0) < self.threshold]
        self.high_cols_ = [c for c in self.cols if cards.get(c, 0) >= self.threshold]
        return self

    def transform(self, X):
        X = pd.DataFrame(X).copy()
        n = len(X)
        low = np.zeros((n, self.n_low), dtype=np.float64)
        high = np.zeros((n, self.n_high), dtype=np.float64)
        for i in range(n):
            for col in self.low_cols_:
                token = f"{col}={_as_token(X.iloc[i][col])}"
                j = _hash_bucket(token, self.algo, self.n_low)
                low[i, j] += 1.0
            for col in self.high_cols_:
                token = f"{col}={_as_token(X.iloc[i][col])}"
                j = _hash_bucket(token, self.algo, self.n_high)
                high[i, j] += 1.0
        mat = np.concatenate([low, high], axis=1)
        colnames = [f"COL_{k+1}" for k in range(mat.shape[1])]
        return pd.DataFrame(mat, columns=colnames, index=X.index)

