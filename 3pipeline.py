def make_baseline_row(X: pd.DataFrame) -> pd.DataFrame:
    baseline = {}
    for col in X.columns:
        s = X[col]
        if pd.api.types.is_numeric_dtype(s):
            baseline[col] = 0
        else:
            baseline[col] = safe_mode(s)
    return pd.DataFrame([baseline])

