@dataclass(frozen=True)
class EncoderSpec:
    name: str
    kind: str  # 'unsupervised' | 'supervised'
    builder: callable  # (cat_cols) -> encoder

def _make_onehot_ct(cat_cols: List[str], drop: Optional[str]) -> ColumnTransformer:
    # handle_unknown='ignore' por exigência do experimento
    # saída densa para compatibilidade com MLP/SVM
    try:
        ohe = OneHotEncoder(handle_unknown="ignore", drop=drop, sparse_output=False)
    except TypeError:
        ohe = OneHotEncoder(handle_unknown="ignore", drop=drop, sparse=False)
    return ColumnTransformer(
        transformers=[("cat", ohe, cat_cols)],
        remainder="passthrough",
    )

def build_encoder_specs(cat_cols: List[str], X_train: pd.DataFrame, card_threshold: int) -> List[EncoderSpec]:
    cards = compute_cardinalities(X_train, cat_cols)
    all_lt = all(cards[c] < card_threshold for c in cat_cols)

    specs: List[EncoderSpec] = []

    # Não supervisionados
    specs.append(EncoderSpec("onehot", "unsupervised", lambda cc: _make_onehot_ct(cc, drop=None)))
    specs.append(EncoderSpec("dummy",  "unsupervised", lambda cc: _make_onehot_ct(cc, drop="first")))
    specs.append(EncoderSpec("count",     "unsupervised", lambda cc: ce.CountEncoder(cols=cc)))
    specs.append(EncoderSpec("frequency", "unsupervised", lambda cc: ce.CountEncoder(cols=cc, normalize=True)))
    specs.append(EncoderSpec("ordinal",   "unsupervised", lambda cc: ce.OrdinalEncoder(cols=cc)))
    specs.append(EncoderSpec("helmert",   "unsupervised", lambda cc: ce.HelmertEncoder(cols=cc)))
    specs.append(EncoderSpec("binary",    "unsupervised", lambda cc: ce.BinaryEncoder(cols=cc)))

    # Hashing (14 nomes possíveis; por base executa subconjunto)
    if all_lt:
        for algo in ["md5", "sha256"]:
            specs.append(EncoderSpec(f"hash_{algo}_8_grouped_alllt100", "unsupervised",
                                     lambda cc, a=algo: HashGroupedEncoder(cols=cc, algo=a, n_components=8)))
            specs.append(EncoderSpec(f"hash_{algo}_8_separate_alllt100", "unsupervised",
                                     lambda cc, a=algo: HashSeparateEncoder(cols=cc, algo=a, n_components=8)))
    else:
        for algo in ["md5", "sha256"]:
            specs.append(EncoderSpec(f"hash_{algo}_8_grouped_anyge100", "unsupervised",
                                     lambda cc, a=algo: HashGroupedEncoder(cols=cc, algo=a, n_components=8)))
            specs.append(EncoderSpec(f"hash_{algo}_8_separate_anyge100", "unsupervised",
                                     lambda cc, a=algo: HashSeparateEncoder(cols=cc, algo=a, n_components=8)))
            specs.append(EncoderSpec(f"hash_{algo}_32_grouped_anyge100", "unsupervised",
                                     lambda cc, a=algo: HashGroupedEncoder(cols=cc, algo=a, n_components=32)))
            specs.append(EncoderSpec(f"hash_{algo}_32_separate_anyge100", "unsupervised",
                                     lambda cc, a=algo: HashSeparateEncoder(cols=cc, algo=a, n_components=32)))
            specs.append(EncoderSpec(f"hash_{algo}_mixed_grouped_anyge100", "unsupervised",
                                     lambda cc, a=algo: HashMixedGroupedEncoder(cols=cc, algo=a,
                                                                              threshold=card_threshold,
                                                                              n_low=8, n_high=32)))

    # Supervisionados
    specs.append(EncoderSpec("catboost",    "supervised", lambda cc: ce.CatBoostEncoder(cols=cc)))
    specs.append(EncoderSpec("target",      "supervised", lambda cc: ce.TargetEncoder(cols=cc)))
    specs.append(EncoderSpec("leaveoneout", "supervised", lambda cc: ce.LeaveOneOutEncoder(cols=cc)))

    return specs

