# Funções auxiliares (robustas a missing) e relatório
# =========================================================

def _non_null(series: pd.Series) -> pd.Series:
    """Retorna apenas valores não-nulos."""
    return series.dropna()


def _n_unique_non_null(series: pd.Series) -> int:
    """Número de valores distintos desconsiderando ausências."""
    return int(_non_null(series).nunique())


def _is_numeric(series: pd.Series) -> bool:
    """Indica se a série é numérica (dtype numérico)."""
    return pd.api.types.is_numeric_dtype(series)


def _is_dichotomous(series: pd.Series) -> bool:
    """Indica se a série possui exatamente 2 valores distintos (não-nulos)."""
    return _n_unique_non_null(series) == 2


def _is_discrete_numeric(series: pd.Series) -> bool:
    """Considera discreto se todos os valores não-nulos forem inteiros.

    Observação: lida com o caso de colunas inteiras com missing, que podem ser
    convertidas para float pelo pandas.
    """
    if not _is_numeric(series):
        return False

    x = _non_null(series)
    if x.empty:
        return False

    x = x.astype(float)
    return bool(np.isclose(x % 1, 0.0, atol=1e-12).all())


def _min_max(series: pd.Series) -> Tuple[Optional[float], Optional[float]]:
    """Retorna (min, max) para séries numéricas; caso contrário, (None, None)."""
    x = _non_null(series)
    if x.empty or (not _is_numeric(series)):
        return None, None
    return float(x.min()), float(x.max())


def _levels(series: pd.Series, max_levels: int = 30) -> str:
    """Lista valores distintos (até max_levels), útil para exibir opções de resposta."""
    x = _non_null(series)
    if x.empty:
        return ""

    vals = list(pd.unique(x))
    try:
        vals = sorted(vals)
    except Exception:
        pass

    if len(vals) > max_levels:
        return ", ".join(map(str, vals[:max_levels])) + f", ... (+{len(vals) - max_levels})"
    return ", ".join(map(str, vals))


def _bold(text: str) -> str:
    return f"**{text}**"


def _red(html_text: str) -> str:
    # Renderiza em HTML (Jupyter/Colab)
    return f"<span style='color:#d62728; font-weight:600'>{html_text}</span>"


def format_attr_name(data: pd.DataFrame, col: str) -> str:
    """Formata o nome do atributo em negrito e destaca cardinalidade 1 em vermelho."""
    nunq = _n_unique_non_null(data[col])
    name = _bold(col)
    if nunq == 1:
        name = _red(name)
    return name


def _to_html(df_: pd.DataFrame) -> str:
    return df_.to_html(index=False, escape=False)


def _section(title: str) -> None:
    display(HTML(f"<h4 style='margin:14px 0 6px 0'>{title}</h4>"))


def _tipo_atributo(series: pd.Series) -> str:
    """Tipagem simples para relatório (inclui atributo classe)."""
    nunq = _n_unique_non_null(series)
    if nunq == 0:
        return "Vazio"

    if _is_numeric(series):
        if nunq == 2:
            return "Dicotômico numérico"
        return "Numérico discreto" if _is_discrete_numeric(series) else "Numérico contínuo"

    if nunq == 2:
        return "Dicotômico nominal"
    return "Categórico nominal"


def to_html_com_titulo(df_: pd.DataFrame, titulo: str) -> str:
    """Converte um DataFrame para HTML e insere um caption no topo."""
    html = df_.to_html(index=False, escape=False)
    return html.replace(
        '<table border="1" class="dataframe">',
        '<table border="1" class="dataframe">'
        "<caption style='caption-side:top; font-weight:600; text-align:left'>"
        f"{titulo}</caption>",
    )


